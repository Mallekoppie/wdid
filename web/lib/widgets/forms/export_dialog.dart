import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../../models/export_bundle.dart';
import '../../state/app_state.dart';
import '../../theme/app_tokens.dart';
import '../../utils/time_utils.dart';
import 'dialog_frame.dart';

Future<void> showExportDialog(
  BuildContext context, {
  required AppState state,
  required DateTime start,
  required DateTime end,
  String checkInId = '',
}) {
  return showDialog<void>(
    context: context,
    builder: (context) => _ExportDialog(
      state: state,
      start: start,
      end: end,
      checkInId: checkInId,
    ),
  );
}

class _ExportDialog extends StatefulWidget {
  const _ExportDialog({
    required this.state,
    required this.start,
    required this.end,
    this.checkInId = '',
  });

  final AppState state;
  final DateTime start;
  final DateTime end;
  final String checkInId;

  @override
  State<_ExportDialog> createState() => _ExportDialogState();
}

class _ExportDialogState extends State<_ExportDialog> {
  ExportBundle? _bundle;
  String? _prompt;
  String? _error;
  String _file = 'summary.md';

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    try {
      final results = await Future.wait<Object>([
        widget.state.buildExport(
          widget.start,
          widget.end,
          checkInId: widget.checkInId,
        ),
        widget.state.buildPrompt(
          widget.start,
          widget.end,
          checkInId: widget.checkInId,
        ),
      ]);
      if (!mounted) return;
      setState(() {
        _bundle = results[0] as ExportBundle;
        _prompt = results[1] as String;
        _file = _bundle!.files.keys.first;
      });
    } catch (error) {
      if (!mounted) return;
      setState(() => _error = error.toString());
    }
  }

  Future<void> _copy(String text, String label) async {
    await Clipboard.setData(ClipboardData(text: text));
    if (!mounted) return;
    ScaffoldMessenger.of(context)
        .showSnackBar(SnackBar(content: Text('$label copied to clipboard')));
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final scheme = theme.colorScheme;
    final bundle = _bundle;
    return DialogFrame(
      title: 'Export period',
      subtitle: '${formatRange(widget.start, widget.end)} · AI-ready bundle',
      icon: Icons.file_download_outlined,
      maxWidth: 820,
      content: _error != null
          ? Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                FormError(message: _error!),
                const SizedBox(height: AppSpacing.md),
                Text(
                  'The export is generated by SummaryService. '
                  'Reconnect the service and try again.',
                  style: theme.textTheme.bodySmall?.copyWith(
                    color: scheme.onSurfaceVariant,
                  ),
                ),
              ],
            )
          : bundle == null
          ? const Padding(
              padding: EdgeInsets.symmetric(vertical: 48),
              child: Center(child: CircularProgressIndicator()),
            )
          : Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                Container(
                  padding: const EdgeInsets.symmetric(
                    horizontal: 10,
                    vertical: 8,
                  ),
                  decoration: BoxDecoration(
                    color: scheme.surfaceContainerLow,
                    borderRadius: BorderRadius.circular(AppRadius.input),
                    border: Border.all(color: scheme.outlineVariant),
                  ),
                  child: Row(
                    children: [
                      Icon(
                        Icons.folder_outlined,
                        size: 16,
                        color: scheme.onSurfaceVariant,
                      ),
                      const SizedBox(width: 8),
                      Text(
                        bundle.directory,
                        style: theme.textTheme.bodySmall?.copyWith(
                          fontFamily: 'monospace',
                        ),
                      ),
                      const Spacer(),
                      Text(
                        '${bundle.files.length} files',
                        style: theme.textTheme.labelSmall?.copyWith(
                          color: scheme.onSurfaceVariant,
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: AppSpacing.md),
                Wrap(
                  spacing: 6,
                  runSpacing: 6,
                  children: [
                    for (final file in bundle.files.keys)
                      ChoiceChip(
                        label: Text(file),
                        selected: _file == file,
                        showCheckmark: false,
                        onSelected: (_) => setState(() => _file = file),
                      ),
                  ],
                ),
                const SizedBox(height: AppSpacing.md),
                Container(
                  height: 320,
                  padding: const EdgeInsets.all(AppSpacing.md),
                  decoration: BoxDecoration(
                    color: scheme.surfaceContainerLowest,
                    borderRadius: BorderRadius.circular(AppRadius.input),
                    border: Border.all(color: scheme.outlineVariant),
                  ),
                  child: SingleChildScrollView(
                    child: SelectableText(
                      bundle.files[_file] ?? '',
                      style: theme.textTheme.bodySmall?.copyWith(
                        fontFamily: 'monospace',
                        height: 1.45,
                      ),
                    ),
                  ),
                ),
              ],
            ),
      actions: Row(
        children: [
          TextButton.icon(
            onPressed: _prompt == null ? null : () => _copy(_prompt!, 'Prompt'),
            icon: const Icon(Icons.copy_all, size: 16),
            label: const Text('Copy prompt'),
          ),
          const SizedBox(width: 6),
          TextButton.icon(
            onPressed: bundle == null
                ? null
                : () => _copy(bundle.files[_file] ?? '', _file),
            icon: const Icon(Icons.copy, size: 16),
            label: const Text('Copy file'),
          ),
          const Spacer(),
          FilledButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }
}
