class CheckinsScreen extends StatelessWidget {
  const CheckinsScreen({super.key});

  Future<void> _create(BuildContext context) async {
    final state = AppStateScope.read(context);
    final checkIn = await showCheckInDialog(context, state: state);
    if (checkIn != null && context.mounted) {
      context.go('/checkins/${checkIn.id}');
    }
  }

  String _excerpt(String markdown) {
    final plain = markdown
        .replaceAll(RegExp(r'[#>*`\-]'), '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
    if (plain.isEmpty) return 'No summary yet.';
    return plain.length > 160 ? '${plain.substring(0, 160)}…' : plain;
  }

  @override
  Widget build(BuildContext context) {
    final state = AppStateScope.of(context);
    final theme = Theme.of(context);
    final scheme = theme.colorScheme;
    final checkIns = state.checkIns;

    return ScreenBody(
      child: PageScaffold(
        child: ListView(
          children: [
            Row(
              children: [
                Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Check-ins', style: theme.textTheme.headlineSmall),
                    const SizedBox(height: 2),
                    Text(
                      state.latestCheckIn == null
                          ? 'Turn captured work into a review-ready period report.'
                          : '${state.daysSinceCheckIn} days since the last check-in · '
                              '${checkIns.length} total',
                      style: theme.textTheme.bodySmall?.copyWith(
                        color: scheme.onSurfaceVariant,
                        fontFeatures: tabularFigures,
                      ),
                    ),
                  ],
                ),
                const Spacer(),
                FilledButton.icon(
                  onPressed: () => unawaited(_create(context)),
                  icon: const Icon(Icons.add, size: 16),
                  label: const Text('Create check-in'),
                ),
              ],
            ),
            const SizedBox(height: AppSpacing.lg),
            if (checkIns.isEmpty)
              Panel(
                child: EmptyState(
                  icon: Icons.event_note_outlined,
                  title: 'No check-ins yet',
                  message:
                      'A check-in snapshots the period since the previous one and '
                      'turns it into a portable summary.',
                  action: FilledButton.icon(
                    onPressed: () => unawaited(_create(context)),
                    icon: const Icon(Icons.add, size: 16),
                    label: const Text('Create check-in'),
                  ),
                ),
              )
            else
              for (final checkIn in checkIns) ...[
                _CheckInCard(
                  checkIn: checkIn,
                  excerpt: _excerpt(checkIn.summaryMarkdown),
                  support: supportMinutes(
                    entriesInRange(
                      state.workItems,
                      checkIn.periodStart,
                      checkIn.periodEnd,
                    ),
                  ),
                  onTap: () => context.go('/checkins/${checkIn.id}'),
                ),
                const SizedBox(height: AppSpacing.md),
              ],
            const SizedBox(height: AppSpacing.md),
            Text(
              'Final check-ins become the boundary for the next period. '
              'Exports are generated by SummaryService.',
              style: theme.textTheme.labelSmall?.copyWith(
                color: scheme.onSurfaceVariant,
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class _CheckInCard extends StatelessWidget {
  const _CheckInCard({
    required this.checkIn,
    required this.excerpt,
    required this.support,
    required this.onTap,
  });

  final CheckIn checkIn;
  final String excerpt;
  final int support;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final scheme = theme.colorScheme;
    final totals = checkIn.totals;
    return Panel(
      onTap: onTap,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            children: [
              Icon(
                Icons.event_note_outlined,
                size: 17,
                color: checkIn.isFinal ? scheme.tertiary : scheme.primary,
              ),
              const SizedBox(width: 8),
              Expanded(
                child: Text(
                  formatRange(checkIn.periodStart, checkIn.periodEnd),
                  style: theme.textTheme.titleMedium?.copyWith(
                    fontFeatures: tabularFigures,
                  ),
                ),
              ),
              CheckInStateBadge(state: checkIn.state),
              const SizedBox(width: 6),
              Icon(
                Icons.chevron_right,
                size: 18,
                color: scheme.onSurfaceVariant,
              ),
            ],
          ),
          const SizedBox(height: 6),
          Text(
            excerpt,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
            style: theme.textTheme.bodySmall?.copyWith(
              color: scheme.onSurfaceVariant,
            ),
          ),
          const SizedBox(height: AppSpacing.md),
          Wrap(
            spacing: AppSpacing.lg,
            runSpacing: 6,
            children: [
              _Metric(
                label: 'logged',
                value: formatDuration(totals.minutes),
              ),
              _Metric(
                label: 'days',
                value: '${checkIn.daysCovered}',
              ),
              _Metric(
                label: 'initiatives',
                value: '${totals.byInitiative.length}',
              ),
              _Metric(
                label: 'support',
                value: formatDuration(support),
              ),
              _Metric(
                label: 'created',
                value: formatShortDate(checkIn.createdAt),
              ),
            ],
          ),
        ],
      ),
    );
  }
}

class _Metric extends StatelessWidget {
  const _Metric({required this.label, required this.value});

  final String label;
  final String value;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final scheme = theme.colorScheme;
    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        Text(
          value,
          style: theme.textTheme.labelMedium?.copyWith(
            fontWeight: FontWeight.w600,
            fontFeatures: tabularFigures,
          ),
        ),
        const SizedBox(width: 4),
        Text(
          label,
          style: theme.textTheme.labelSmall?.copyWith(
            color: scheme.onSurfaceVariant,
          ),
        ),
      ],
    );
  }
}
